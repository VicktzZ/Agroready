import { ArrowLeft, Printer } from 'lucide-react';
import { useState } from 'react';
import type { ReactNode } from 'react';
import { useNavigate, useParams } from 'react-router';
import { useApi } from '../api';
import { useAuth } from '../auth';
import { Placar } from '../components/Checklist';
import { Marca } from '../Shell';
import type { AvaliacaoCarbonoSalva, AvaliacaoExportSalva, ItemChecklist, Lang } from '../types';
import { Button, Estado, fmtDataHora, fmtDia, fmtNum, Segmentado, StatusBadge } from '../ui';

/* Relatórios para imprimir ou salvar em PDF pelo próprio navegador (window.print). */

function Pagina({ titulo, emitido, lang = 'pt', extra, children }: { titulo: string; emitido: string; lang?: Lang; extra?: ReactNode; children: ReactNode }) {
  const navegar = useNavigate();
  const { usuario } = useAuth();
  const pt = lang === 'pt';
  return (
    <div className="relatorio-pagina">
      <div className="row entre nao-imprimir">
        <Button variante="ghost" icone={<ArrowLeft size={16} />} onClick={() => navegar(-1)}>
          Voltar
        </Button>
        <div className="row">
          {extra}
          <Button icone={<Printer size={16} />} onClick={() => window.print()}>
            {pt ? 'Imprimir / salvar em PDF' : 'Print / save as PDF'}
          </Button>
        </div>
      </div>
      <article className="relatorio">
        <header className="relatorio__topo">
          <div>
            <h1>{titulo}</h1>
            <p className="muted">
              {pt ? 'Avaliado em' : 'Assessed on'} {fmtDataHora(emitido)} · {pt ? 'por' : 'by'} {usuario?.nome}
            </p>
          </div>
          <div className="brand">
            <Marca />
          </div>
        </header>
        {children}
        <footer className="rodape-relatorio">
          {pt
            ? 'Documento gerado pelo AgroReady (projeto acadêmico — Fatec Cotia). Regras, critérios e fatores são ilustrativos e não substituem a consulta às normas oficiais nem a análise de um profissional habilitado.'
            : 'Document generated by AgroReady (academic project — Fatec Cotia). Rules, criteria and factors are illustrative and do not replace official regulations or the analysis of a qualified professional.'}
        </footer>
      </article>
    </div>
  );
}

function Tabela({ items, lang = 'pt' }: { items: ItemChecklist[]; lang?: Lang }) {
  const pt = lang === 'pt';
  return (
    <div className="table-wrap">
      <table>
        <thead>
          <tr>
            <th>{pt ? 'Exigência' : 'Requirement'}</th>
            <th>{pt ? 'Situação' : 'Status'}</th>
            <th>{pt ? 'Observação' : 'Note'}</th>
          </tr>
        </thead>
        <tbody>
          {items.map((i) => (
            <tr key={i.id}>
              <td>{i.label}</td>
              <td>
                <StatusBadge status={i.status} lang={lang} />
              </td>
              <td>{i.note}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

const Fato = ({ rotulo, children }: { rotulo: string; children: ReactNode }) => (
  <div>
    <dt>{rotulo}</dt>
    <dd>{children}</dd>
  </div>
);

export function RelatorioExportacao() {
  const { id } = useParams();
  const avaliacao = useApi<AvaliacaoExportSalva>(`/export/avaliacoes/${id}`);
  const [lang, setLang] = useState<Lang>('pt');
  const pt = lang === 'pt';

  return (
    <Estado {...avaliacao}>
      {(a) => {
        const r = a.resultado![lang];
        const laudo = a.laudo.resumo;
        const lista = (itens?: string[]) => (itens?.length ? itens.join(', ') : pt ? 'nenhuma' : 'none');
        return (
          <Pagina
            titulo={pt ? 'Relatório de prontidão para exportação' : 'Export readiness report'}
            emitido={a.createdAt}
            lang={lang}
            extra={
              <Segmentado
                rotulo="Idioma do relatório"
                valor={lang}
                onChange={setLang}
                opcoes={[
                  { valor: 'pt', rotulo: 'Português' },
                  { valor: 'en', rotulo: 'English' },
                ]}
              />
            }
          >
            <section>
              <h2>{pt ? 'Operação' : 'Shipment'}</h2>
              <dl className="fatos">
                <Fato rotulo={pt ? 'Cultura' : 'Crop'}>{pt ? a.cultura.nome : a.cultura.nomeEn}</Fato>
                <Fato rotulo={pt ? 'Destino' : 'Destination'}>{pt ? a.destino.nome : a.destino.nomeEn}</Fato>
                <Fato rotulo={pt ? 'Embarque previsto' : 'Planned shipment'}>{fmtDia(a.embarque)}</Fato>
                <Fato rotulo={pt ? 'Laudo' : 'Report'}>{a.laudo.numero ? `Nº ${a.laudo.numero}` : (a.laudo.titulo ?? '—')}</Fato>
                <Fato rotulo={pt ? 'Propriedade' : 'Farm'}>{laudo?.propriedade ?? '—'}</Fato>
                <Fato rotulo={pt ? 'Município' : 'Municipality'}>{laudo?.local ?? '—'}</Fato>
              </dl>
            </section>

            <section>
              <h2>{pt ? 'Resultado' : 'Result'}</h2>
              <Placar resumo={r.resumo} total={r.items.length} lang={lang} unidade={pt ? 'exigências atendidas' : 'requirements met'} />
            </section>

            <section>
              <h2>{pt ? 'Exigências do destino' : 'Destination requirements'}</h2>
              <Tabela items={r.items} lang={lang} />
            </section>

            <section>
              <h2>{pt ? 'Achados do laudo' : 'Report findings'}</h2>
              <dl className="fatos">
                <Fato rotulo={pt ? 'Pragas' : 'Pests'}>{lista(laudo?.pragas)}</Fato>
                <Fato rotulo={pt ? 'Doenças' : 'Diseases'}>{lista(laudo?.doencas)}</Fato>
                <Fato rotulo={pt ? 'Última inspeção' : 'Latest inspection'}>{fmtDia(laudo?.ultimaInspecao)}</Fato>
              </dl>
            </section>
          </Pagina>
        );
      }}
    </Estado>
  );
}

export function RelatorioCarbono() {
  const { id } = useParams();
  const avaliacao = useApi<AvaliacaoCarbonoSalva>(`/carbono/avaliacoes/${id}`);
  const simNao = (v: boolean) => (v ? 'Sim' : 'Não');

  return (
    <Estado {...avaliacao}>
      {(a) => {
        const d = a.dados!;
        const r = a.resultado!;
        const e = r.estimativa;
        return (
          <Pagina titulo="Relatório de elegibilidade a créditos de carbono" emitido={a.createdAt}>
            <section>
              <h2>Propriedade</h2>
              <dl className="fatos">
                <Fato rotulo="Nome">{a.nome}</Fato>
                <Fato rotulo="Bioma">{d.biomaNome}</Fato>
                <Fato rotulo="Área total">{fmtNum(d.area)} ha</Fato>
                <Fato rotulo="Reserva Legal atual">{fmtNum(d.rl)}%</Fato>
                <Fato rotulo="CAR/SICAR ativo">{simNao(d.car)}</Fato>
                <Fato rotulo="Desmatamento recente">{simNao(d.desmatamento)}</Fato>
                <Fato rotulo="Padrão de certificação">{d.padrao}</Fato>
                <Fato rotulo="Plano de MRV">{simNao(d.mrv)}</Fato>
                <Fato rotulo="Práticas adotadas">{d.praticasNomes.length ? d.praticasNomes.join('; ') : 'nenhuma'}</Fato>
              </dl>
            </section>

            <section>
              <h2>Resultado</h2>
              <Placar resumo={r.resumo} total={r.items.length} unidade="critérios atendidos" />
            </section>

            <section>
              <h2>Estimativa de créditos (ilustrativa)</h2>
              {e.praticaBase ? (
                <dl className="fatos">
                  <Fato rotulo="Área produtiva">{fmtNum(e.areaProdutivaHa)} ha</Fato>
                  <Fato rotulo="Prática de referência">
                    {e.praticaBase.nome} ({fmtNum(e.praticaBase.fatorTco2eHaAno)} tCO2e/ha/ano)
                  </Fato>
                  <Fato rotulo="Potencial bruto">{fmtNum(e.potencialTco2eAno)} tCO2e/ano</Fato>
                  <Fato rotulo="Buffer de não permanência">{e.bufferPct}%</Fato>
                  <Fato rotulo="Créditos estimados">~{fmtNum(e.creditosAno)} por ano</Fato>
                </dl>
              ) : (
                <p className="muted">Sem prática de baixo carbono adotada: não há estimativa.</p>
              )}
            </section>

            <section>
              <h2>Critérios de elegibilidade</h2>
              <Tabela items={r.items} />
            </section>
          </Pagina>
        );
      }}
    </Estado>
  );
}
